def ensure_spec_text(spec_path: Path | None, refresh: bool) -> str:
    if spec_path is not None:
        return spec_path.read_text(encoding="utf-8")

    cache_path = spec_cache_path()
    if cache_path.exists() and not refresh:
        return cache_path.read_text(encoding="utf-8")

    request = urllib.request.Request(
        OFFICIAL_SPEC_URL,
        headers={"User-Agent": "Mozilla/5.0"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        text = response.read().decode("utf-8")

    cache_path.write_text(text, encoding="utf-8")
    return text


def safe_eval_int(expr: str) -> int:
    stripped = expr.strip()
    if not re.fullmatch(r"[0-9+ ()]+", stripped):
        raise ValueError(f"unsupported constant expression: {expr}")
    return int(eval(stripped, {"__builtins__": {}}, {}))


def camel_to_snake(text: str) -> str:
    if not text:
        return text
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    text = text.replace("__", "_")
    return text.lower()


def clean_field_name(name: str) -> str:
    if name.startswith("m_"):
        name = name[2:]
    return camel_to_snake(name)


def enum_name_to_slug(enum_name: str) -> str:
    core = enum_name.removeprefix("ePacketId")
    return camel_to_snake(core)


def enum_name_to_label(enum_name: str) -> str:
    return enum_name.removeprefix("ePacketId")


def parse_spec_text(text: str) -> tuple[dict[str, int], dict[int, str], dict[str, list[dict[str, Any]]], dict[str, list[dict[str, Any]]]]:
    lines = [line.split("//")[0].rstrip() for line in text.splitlines()]

    constants: dict[str, int] = {}
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("static const") and "cs_" in stripped and "=" in stripped:
            left, right = stripped.split("=", 1)
            name = left.split()[-1]
            expr = right.split(";", 1)[0].strip()
            constants[name] = safe_eval_int(expr)

    def parse_block(index: int) -> tuple[list[dict[str, Any]], str, int]:
        items: list[dict[str, Any]] = []
        while index < len(lines):
            stripped = lines[index].strip()
            if not stripped:
                index += 1
                continue
            if stripped.startswith("static const"):
                index += 1
                continue
            if stripped in {"};", "}"}:
                return items, stripped, index + 1
            if stripped.startswith("} "):
                return items, stripped, index + 1
            if stripped == "struct" and index + 1 < len(lines) and lines[index + 1].strip() == "{":
                nested_fields, end_line, next_index = parse_block(index + 2)
                alias = end_line[1:].strip().rstrip(";").strip()
                items.append({"kind": "variant", "name": alias, "fields": nested_fields})
                index = next_index
                continue
            if stripped.startswith("struct ") and index + 1 < len(lines) and lines[index + 1].strip() == "{":
                name = stripped.split()[1]
                nested_fields, _, next_index = parse_block(index + 2)
                items.append({"kind": "named_struct", "name": name, "fields": nested_fields})
                index = next_index
                continue
            if ";" in stripped:
                declaration = stripped.rstrip(";")
                parts = declaration.split()
                if len(parts) >= 2:
                    type_name = TYPE_ALIASES.get(parts[0], parts[0])
                    rest = "".join(parts[1:])
                    field_name = rest.split("[", 1)[0]
                    dimensions: list[str] = []
                    remainder = rest[len(field_name) :]
                    while remainder.startswith("["):
                        end = remainder.index("]")
                        dimensions.append(remainder[1:end])
                        remainder = remainder[end + 1 :]
                    items.append(
                        {
                            "kind": "field",
                            "type": type_name,
                            "name": field_name,
                            "dims": dimensions,
                        }
                    )
                index += 1
                continue
            index += 1
        return items, "", index

    structs: dict[str, list[dict[str, Any]]] = {}
    unions: dict[str, list[dict[str, Any]]] = {}
    index = 0
    while index < len(lines):
        stripped = lines[index].strip()
        if stripped.startswith("struct ") and index + 1 < len(lines) and lines[index + 1].strip() == "{":
            name = stripped.split()[1]
            fields, _, index = parse_block(index + 2)
            structs[name] = [field for field in fields if field["kind"] == "field"]
            continue
        if stripped.startswith("union ") and index + 1 < len(lines) and lines[index + 1].strip() == "{":
            name = stripped.split()[1]
            fields, _, index = parse_block(index + 2)
            unions[name] = fields
            continue
        index += 1

    packet_ids: dict[int, str] = {}
    in_packet_enum = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("enum PacketId"):
            in_packet_enum = True
            continue
        if in_packet_enum and stripped == "};":
            break
        if in_packet_enum and "=" in stripped:
            left, right = stripped.rstrip(",").split("=", 1)
            enum_name = left.strip()
            raw_value = right.strip().split(",")[0].strip()
            if enum_name.startswith("ePacketId") and enum_name != "ePacketIdMax":
                packet_ids[int(raw_value)] = enum_name

    return constants, packet_ids, structs, unions


def resolve_dims(raw_dims: list[str], constants: dict[str, int]) -> list[int]:
    resolved: list[int] = []
    for raw in raw_dims:
        token = raw.strip()
        if token.isdigit():
            resolved.append(int(token))
        else:
            resolved.append(constants[token])
    return resolved


def is_primitive(type_name: str) -> bool:
    canonical = TYPE_ALIASES.get(type_name, type_name)
    return canonical == "char" or canonical in PRIMITIVE_FORMATS


def decode_primitive(type_name: str, payload: bytes, offset: int) -> tuple[Any, int]:
    canonical = TYPE_ALIASES.get(type_name, type_name)
    if canonical == "char":
        if offset + 1 > len(payload):
            raise DecodeError("packet too short while reading char")
        return payload[offset], offset + 1

    fmt = PRIMITIVE_FORMATS[canonical]
    size = struct.calcsize("<" + fmt)
    if offset + size > len(payload):
        raise DecodeError(f"packet too short while reading {canonical}")
    value = struct.unpack_from("<" + fmt, payload, offset)[0]
    return value, offset + size


def size_of_field(
    field: dict[str, Any],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
) -> int:
    return size_of_type(field["type"], resolve_dims(field["dims"], constants), constants, structs, unions)


def size_of_type(
    type_name: str,
    dims: list[int],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
) -> int:
    if dims:
        element_size = size_of_type(type_name, [], constants, structs, unions)
        count = 1
        for dim in dims:
            count *= dim
        return element_size * count

    canonical = TYPE_ALIASES.get(type_name, type_name)
    if canonical == "char":
        return 1
    if canonical in PRIMITIVE_FORMATS:
        return struct.calcsize("<" + PRIMITIVE_FORMATS[canonical])
    if canonical in structs:
        return sum(size_of_field(field, constants, structs, unions) for field in structs[canonical])
    if canonical in unions:
        variant_sizes = []
        for variant in unions[canonical]:
            if variant["kind"] != "variant":
                continue
            variant_sizes.append(
                sum(size_of_field(field, constants, structs, unions) for field in variant["fields"])
            )
        if not variant_sizes:
            raise DecodeError(f"union {canonical} has no variants")
        return max(variant_sizes)
    raise DecodeError(f"unknown type: {type_name}")


def decode_char_array(payload: bytes, offset: int, length: int) -> tuple[str, int]:
    if offset + length > len(payload):
        raise DecodeError("packet too short while reading char array")
    raw = payload[offset : offset + length]
    text = raw.split(b"\x00", 1)[0].decode("utf-8", errors="replace")
    return text, offset + length


def decode_array(
    type_name: str,
    dims: list[int],
    payload: bytes,
    offset: int,
    context: dict[str, Any],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
) -> tuple[Any, int]:
    canonical = TYPE_ALIASES.get(type_name, type_name)
    if canonical == "char" and len(dims) == 1:
        return decode_char_array(payload, offset, dims[0])

    if not dims:
        return decode_type(type_name, payload, offset, context, constants, structs, unions)

    count = dims[0]
    values = []
    for _ in range(count):
        if len(dims) == 1:
            value, offset = decode_type(type_name, payload, offset, context, constants, structs, unions)
        else:
            value, offset = decode_array(
                type_name,
                dims[1:],
                payload,
                offset,
                context,
                constants,
                structs,
                unions,
            )
        values.append(value)
    return values, offset


def decode_event_details(
    payload: bytes,
    offset: int,
    context: dict[str, Any],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
) -> tuple[dict[str, Any], int]:
    union_name = "EventDataDetails"
    variants = {item["name"]: item["fields"] for item in unions[union_name] if item["kind"] == "variant"}
    union_size = size_of_type(union_name, [], constants, structs, unions)
    if offset + union_size > len(payload):
        raise DecodeError("packet too short while reading EventDataDetails")

    raw = payload[offset : offset + union_size]
    event_code = context.get("event_code", "")
    variant_name = EVENT_CODE_TO_VARIANT.get(event_code, "")
    decoded: dict[str, Any] = OrderedDict()
    decoded["event_code"] = event_code
    decoded["event_variant"] = variant_name
    decoded["raw_hex"] = raw.hex()
    decoded["unknown_event_code"] = ""

    for variant, fields in variants.items():
        prefix = camel_to_snake(variant)
        for field in fields:
            decoded[f"{prefix}__{clean_field_name(field['name'])}"] = ""

    if variant_name and variant_name in variants:
        variant_payload_offset = 0
        variant_context = dict(context)
        for field in variants[variant_name]:
            value, variant_payload_offset = decode_type(
                field["type"],
                raw,
                variant_payload_offset,
                variant_context,
                constants,
                structs,
                unions,
                resolve_dims(field["dims"], constants),
            )
            decoded[f"{camel_to_snake(variant_name)}__{clean_field_name(field['name'])}"] = value
    elif event_code not in EVENT_CODES_WITHOUT_DETAILS and event_code:
        decoded["unknown_event_code"] = event_code

    return decoded, offset + union_size


def decode_struct(
    struct_name: str,
    payload: bytes,
    offset: int,
    context: dict[str, Any],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
) -> tuple[dict[str, Any], int]:
    if struct_name not in structs:
        raise DecodeError(f"unknown struct: {struct_name}")

    decoded: dict[str, Any] = OrderedDict()
    local_context = dict(context)
    for field in structs[struct_name]:
        dims = resolve_dims(field["dims"], constants)
        if field["name"] == "m_eventStringCode" and field["type"] == "uint8" and dims == [4]:
            if offset + 4 > len(payload):
                raise DecodeError("packet too short while reading event string code")
            value = payload[offset : offset + 4].decode("ascii", errors="replace")
            offset += 4
        else:
            value, offset = decode_type(
                field["type"],
                payload,
                offset,
                local_context,
                constants,
                structs,
                unions,
                dims,
            )
        decoded[field["name"]] = value
        if field["name"] == "m_eventStringCode":
            local_context["event_code"] = value
            decoded["m_eventCode"] = value
    return decoded, offset


def decode_type(
    type_name: str,
    payload: bytes,
    offset: int,
    context: dict[str, Any],
    constants: dict[str, int],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
    dims: list[int] | None = None,
) -> tuple[Any, int]:
    resolved_dims = dims or []
    if resolved_dims:
        return decode_array(type_name, resolved_dims, payload, offset, context, constants, structs, unions)

    canonical = TYPE_ALIASES.get(type_name, type_name)
    if canonical == "EventDataDetails":
        return decode_event_details(payload, offset, context, constants, structs, unions)
    if is_primitive(canonical):
        value, offset = decode_primitive(canonical, payload, offset)
        if canonical == "char":
            value = chr(value)
        return value, offset
    return decode_struct(canonical, payload, offset, context, constants, structs, unions)


def sanitize_row_value(value: Any) -> Any:
    if isinstance(value, float):
        return round(value, 6)
    if value is None:
        return ""
    return value


def is_scalar_value(value: Any) -> bool:
    return isinstance(value, (str, int, float, bool)) or value is None


class CsvSinkManager:
    def __init__(self, output_dir: Path) -> None:
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self._files: dict[str, Any] = {}
        self._writers: dict[str, csv.DictWriter] = {}
        self._fieldnames: dict[str, list[str]] = {}

    def write_row(self, table_name: str, row: OrderedDict[str, Any]) -> None:
        path = self.output_dir / f"{table_name}.csv"
        if table_name not in self._writers:
            handle = path.open("w", encoding="utf-8", newline="")
            fieldnames = list(row.keys())
            writer = csv.DictWriter(handle, fieldnames=fieldnames)
            writer.writeheader()
            self._files[table_name] = handle
            self._writers[table_name] = writer
            self._fieldnames[table_name] = fieldnames

        fieldnames = self._fieldnames[table_name]
        extra_keys = [key for key in row.keys() if key not in fieldnames]
        if extra_keys:
            raise ValueError(
                f"table {table_name} received unexpected columns after initialization: {extra_keys}"
            )

        normalized = {key: sanitize_row_value(row.get(key, "")) for key in fieldnames}
        self._writers[table_name].writerow(normalized)

    def close(self) -> None:
        for handle in self._files.values():
            handle.close()


def flatten_scalar_fields(prefix: str, value: Any, row: OrderedDict[str, Any]) -> None:
    if is_scalar_value(value):
        row[prefix] = value
        return
    if isinstance(value, dict):
        for key, nested in value.items():
            flatten_scalar_fields(f"{prefix}__{clean_field_name(key)}", nested, row)
        return
    if isinstance(value, list):
        if not value:
            row[prefix] = ""
            return
        if all(is_scalar_value(item) for item in value):
            for index, item in enumerate(value):
                row[f"{prefix}_{index}"] = item
            return
    row[prefix] = json.dumps(value, ensure_ascii=True, separators=(",", ":"))


def export_struct_rows(
    table_name: str,
    data: dict[str, Any],
    base_row: OrderedDict[str, Any],
    sink: CsvSinkManager,
) -> None:
    row = OrderedDict(base_row)

    for key, value in data.items():
        if key == "m_header":
            continue
        column = clean_field_name(key)

        if is_scalar_value(value):
            row[column] = value
            continue

        if isinstance(value, dict):
            flatten_scalar_fields(column, value, row)
            continue

        if isinstance(value, list):
            if not value:
                row[column] = ""
                continue
            first = value[0]
            if isinstance(first, dict):
                continue
            if isinstance(first, list):
                continue
            if all(is_scalar_value(item) for item in value):
                for index, item in enumerate(value):
                    row[f"{column}_{index}"] = item
                continue

    sink.write_row(table_name, row)

    for key, value in data.items():
        if key == "m_header" or not isinstance(value, list) or not value:
            continue

        column = clean_field_name(key)
        child_table = f"{table_name}__{column}"

        first = value[0]
        if isinstance(first, dict):
            index_name = ARRAY_INDEX_OVERRIDES.get(column, "item_index")
            for index, item in enumerate(value):
                child_base = OrderedDict(base_row)
                child_base[index_name] = index
                export_struct_rows(child_table, item, child_base, sink)
            continue

        if isinstance(first, list):
            outer_name, inner_name, value_name = MATRIX_INDEX_OVERRIDES.get(
                column,
                ("outer_index", "inner_index", "value"),
            )
            for outer_index, nested_items in enumerate(value):
                for inner_index, nested_value in enumerate(nested_items):
                    child_row = OrderedDict(base_row)
                    child_row[outer_name] = outer_index
                    child_row[inner_name] = inner_index
                    child_row[value_name] = nested_value
                    sink.write_row(child_table, child_row)
            continue


def build_packet_summary_row(
    record: dict[str, Any],
    header: dict[str, Any],
    packet_enum_name: str,
    packet_slug: str,
    packet_struct: str,
    packet_bytes: bytes,
    expected_size: int,
    consumed_size: int,
    decode_error: str,
    include_packet_hex: bool,
) -> OrderedDict[str, Any]:
    row: OrderedDict[str, Any] = OrderedDict((field, "") for field in SUMMARY_FIELD_ORDER)
    row["sequence_id"] = record.get("sequence_id", "")
    row["received_at_ms"] = record.get("received_at_ms", "")
    row["received_at_utc"] = record.get("received_at_utc", "")
    row["source_host"] = record.get("source_host", "")
    row["source_port"] = record.get("source_port", "")
    row["capture_byte_length"] = record.get("byte_length", "")
    row["decoded_byte_length"] = len(packet_bytes)
    row["packet_sha1"] = hashlib.sha1(packet_bytes).hexdigest()
    row["packet_enum_name"] = packet_enum_name
    row["packet_name"] = enum_name_to_label(packet_enum_name) if packet_enum_name else ""
    row["packet_slug"] = packet_slug
    row["packet_struct"] = packet_struct
    row["expected_size"] = expected_size
    row["consumed_size"] = consumed_size
    row["extra_byte_count"] = max(len(packet_bytes) - consumed_size, 0)
    row["decode_error"] = decode_error

    for key, value in header.items():
        if key == "m_eventCode":
            continue
        row[clean_field_name(key)] = value

    if include_packet_hex:
        row["packet_hex"] = packet_bytes.hex()
    return row


def parse_capture(
    input_path: Path,
    output_dir: Path,
    constants: dict[str, int],
    packet_ids: dict[int, str],
    structs: dict[str, list[dict[str, Any]]],
    unions: dict[str, list[dict[str, Any]]],
    include_packet_hex: bool,
) -> tuple[int, int]:
    sink = CsvSinkManager(output_dir)
    processed = 0
    errors = 0

    try:
        with input_path.open("r", encoding="utf-8") as handle:
            for line_number, raw_line in enumerate(handle, start=1):
                line = raw_line.strip()
                if not line:
                    continue

                processed += 1
                try:
                    record = json.loads(line)
                except json.JSONDecodeError as exc:
                    errors += 1
                    row = OrderedDict((field, "") for field in SUMMARY_FIELD_ORDER)
                    if include_packet_hex:
                        row["packet_hex"] = ""
                    row["decode_error"] = f"line {line_number}: invalid json: {exc}"
                    sink.write_row("packet_summary", row)
                    continue

                try:
                    payload_base64 = record["payload_base64"]
                    if not isinstance(payload_base64, str):
                        raise TypeError("payload_base64 must be a string")
                    packet_bytes = base64.b64decode(payload_base64, validate=True)
                except (KeyError, TypeError, ValueError, base64.binascii.Error) as exc:
                    errors += 1
                    row = OrderedDict((field, "") for field in SUMMARY_FIELD_ORDER)
                    if include_packet_hex:
                        row["packet_hex"] = ""
                    row["sequence_id"] = record.get("sequence_id", "")
                    row["received_at_ms"] = record.get("received_at_ms", "")
                    row["received_at_utc"] = record.get("received_at_utc", "")
                    row["source_host"] = record.get("source_host", "")
                    row["source_port"] = record.get("source_port", "")
                    row["capture_byte_length"] = record.get("byte_length", "")
                    row["decode_error"] = f"line {line_number}: invalid payload_base64: {exc}"
                    sink.write_row("packet_summary", row)
                    continue

                header_size = size_of_type("PacketHeader", [], constants, structs, unions)
                decode_error = ""
                packet_data: dict[str, Any] | None = None
                packet_struct = ""
                packet_enum_name = ""
                packet_slug = ""
                header: dict[str, Any] = {}
                expected_size = 0
                consumed_size = 0

                try:
                    header, offset = decode_struct(
                        "PacketHeader",
                        packet_bytes,
                        0,
                        {},
                        constants,
                        structs,
                        unions,
                    )
                    packet_id = int(header["m_packetId"])
                    packet_enum_name = packet_ids.get(packet_id, f"ePacketIdUnknown{packet_id}")
                    packet_slug = enum_name_to_slug(packet_enum_name)
                    packet_struct = PACKET_STRUCT_OVERRIDES.get(packet_id, "")
                    if not packet_struct:
                        raise DecodeError(f"unsupported packet id: {packet_id}")

                    packet_data, consumed_size = decode_struct(
                        packet_struct,
                        packet_bytes,
                        0,
                        {},
                        constants,
                        structs,
                        unions,
                    )
                    expected_size = size_of_type(packet_struct, [], constants, structs, unions)
                except DecodeError as exc:
                    decode_error = str(exc)
                    errors += 1
                    if not header and len(packet_bytes) >= header_size:
                        try:
                            header, _ = decode_struct(
                                "PacketHeader",
                                packet_bytes,
                                0,
                                {},
                                constants,
                                structs,
                                unions,
                            )
                            packet_id = int(header["m_packetId"])
                            packet_enum_name = packet_ids.get(packet_id, f"ePacketIdUnknown{packet_id}")
                            packet_slug = enum_name_to_slug(packet_enum_name)
                            packet_struct = PACKET_STRUCT_OVERRIDES.get(packet_id, "")
                            if packet_struct:
                                expected_size = size_of_type(packet_struct, [], constants, structs, unions)
                        except DecodeError:
                            header = {}

                summary_row = build_packet_summary_row(
                    record,
                    header,
                    packet_enum_name,
                    packet_slug,
                    packet_struct,
                    packet_bytes,
                    expected_size,
                    consumed_size,
                    decode_error,
                    include_packet_hex,
                )
                sink.write_row("packet_summary", summary_row)

                if decode_error or packet_data is None:
                    continue

                base_row = OrderedDict()
                for key in (
                    "sequence_id",
                    "received_at_ms",
                    "received_at_utc",
                    "source_host",
                    "source_port",
                    "packet_name",
                    "packet_slug",
                    "packet_struct",
                    "packet_id",
                    "packet_version",
                    "session_uid",
                    "session_time",
                    "frame_identifier",
                    "overall_frame_identifier",
                    "player_car_index",
                    "secondary_player_car_index",
                ):
                    base_row[key] = summary_row.get(key, "")

                export_struct_rows(packet_slug, packet_data, base_row, sink)
    finally:
        sink.close()

    return processed, errors


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    if not args.input.exists():
        print(f"Input file not found: {args.input}", file=sys.stderr)
        return 2

    try:
        spec_text = ensure_spec_text(args.spec, refresh=args.refresh_spec)
        constants, packet_ids, structs, unions = parse_spec_text(spec_text)
    except Exception as exc:
        print(f"Failed to load F1 25 structure specification: {exc}", file=sys.stderr)
        return 2

    output_dir = args.output_dir or default_output_dir(args.input)
    output_dir.mkdir(parents=True, exist_ok=True)

    try:
        processed, errors = parse_capture(
            args.input,
            output_dir,
            constants,
            packet_ids,
            structs,
            unions,
            include_packet_hex=args.include_packet_hex,
        )
    except Exception as exc:
        print(f"Failed while parsing capture: {exc}", file=sys.stderr)
        return 1

    print(f"Output directory: {output_dir.resolve()}")
    print(f"Processed packets: {processed}")
    print(f"Packets with decode issues: {errors}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
