#!/usr/bin/env python3
from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import json
import struct
import sys
from pathlib import Path


HEADER_FORMAT = "<HBBBBBQfIIBB"
HEADER_SIZE = struct.calcsize(HEADER_FORMAT)
EVENT_PACKET_ID = 3

PACKET_ID_NAMES = {
    0: "Motion",
    1: "Session",
    2: "LapData",
    3: "Event",
    4: "Participants",
    5: "CarSetups",
    6: "CarTelemetry",
    7: "CarStatus",
    8: "FinalClassification",
    9: "LobbyInfo",
    10: "CarDamage",
    11: "SessionHistory",
    12: "TyreSets",
    13: "MotionEx",
    14: "TimeTrial",
}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Decode F1 25 capture JSONL into validation-friendly CSV files."
    )
    parser.add_argument(
        "input",
        type=Path,
        help="Path to the JSONL capture file generated by f1_25_udp_capture.py",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Summary CSV output path. Defaults to <input_stem>.csv",
    )
    parser.add_argument(
        "--include-payload-hex",
        action="store_true",
        help="Include the full packet and payload hex columns in the summary CSV.",
    )
    parser.add_argument(
        "--explode-bytes",
        action="store_true",
        help="Write a second CSV with one row per byte for low-level validation.",
    )
    parser.add_argument(
        "--bytes-output",
        type=Path,
        help="Optional output path for the per-byte CSV. Defaults to <input_stem>_bytes.csv",
    )
    return parser


def default_summary_output(input_path: Path) -> Path:
    return input_path.with_name(f"{input_path.stem}.csv")


def default_bytes_output(input_path: Path) -> Path:
    return input_path.with_name(f"{input_path.stem}_bytes.csv")


def decode_packet_header(packet: bytes) -> dict[str, object]:
    if len(packet) < HEADER_SIZE:
        raise ValueError(f"packet too short for F1 25 header: {len(packet)} bytes")

    (
        packet_format,
        game_year,
        game_major_version,
        game_minor_version,
        packet_version,
        packet_id,
        session_uid,
        session_time,
        frame_identifier,
        overall_frame_identifier,
        player_car_index,
        secondary_player_car_index,
    ) = struct.unpack_from(HEADER_FORMAT, packet, 0)

    return {
        "packet_format": packet_format,
        "game_year": game_year,
        "game_major_version": game_major_version,
        "game_minor_version": game_minor_version,
        "packet_version": packet_version,
        "packet_id": packet_id,
        "packet_name": PACKET_ID_NAMES.get(packet_id, f"Unknown({packet_id})"),
        "session_uid": session_uid,
        "session_time_s": round(session_time, 6),
        "frame_identifier": frame_identifier,
        "overall_frame_identifier": overall_frame_identifier,
        "player_car_index": player_car_index,
        "secondary_player_car_index": secondary_player_car_index,
    }


def decode_event_code(packet: bytes, packet_id: int) -> str:
    if packet_id != EVENT_PACKET_ID or len(packet) < HEADER_SIZE + 4:
        return ""
    raw = packet[HEADER_SIZE : HEADER_SIZE + 4]
    return raw.decode("ascii", errors="replace")


def build_summary_row(
    record: dict[str, object],
    packet_bytes: bytes,
    *,
    include_payload_hex: bool,
) -> dict[str, object]:
    row: dict[str, object] = {
        "sequence_id": record.get("sequence_id"),
        "received_at_ms": record.get("received_at_ms"),
        "received_at_utc": record.get("received_at_utc", ""),
        "source_host": record.get("source_host", ""),
        "source_port": record.get("source_port", ""),
        "capture_byte_length": record.get("byte_length", ""),
        "decoded_byte_length": len(packet_bytes),
        "header_size": HEADER_SIZE,
        "payload_size": max(len(packet_bytes) - HEADER_SIZE, 0),
        "payload_sha1": hashlib.sha1(packet_bytes).hexdigest(),
        "decode_error": "",
    }

    try:
        header = decode_packet_header(packet_bytes)
    except ValueError as exc:
        row.update(
            {
                "header_ok": False,
                "packet_format": "",
                "game_year": "",
                "game_major_version": "",
                "game_minor_version": "",
                "packet_version": "",
                "packet_id": "",
                "packet_name": "",
                "session_uid": "",
                "session_time_s": "",
                "frame_identifier": "",
                "overall_frame_identifier": "",
                "player_car_index": "",
                "secondary_player_car_index": "",
                "event_code": "",
                "decode_error": str(exc),
            }
        )
    else:
        row.update(header)
        row["header_ok"] = True
        row["event_code"] = decode_event_code(packet_bytes, int(header["packet_id"]))

    if include_payload_hex:
        row["packet_hex"] = packet_bytes.hex()
        row["payload_hex"] = packet_bytes[HEADER_SIZE:].hex() if len(packet_bytes) > HEADER_SIZE else ""

    return row


def write_byte_rows(
    writer: csv.DictWriter,
    summary_row: dict[str, object],
    packet_bytes: bytes,
) -> None:
    for absolute_offset, byte_value in enumerate(packet_bytes):
        writer.writerow(
            {
                "sequence_id": summary_row.get("sequence_id", ""),
                "packet_id": summary_row.get("packet_id", ""),
                "packet_name": summary_row.get("packet_name", ""),
                "event_code": summary_row.get("event_code", ""),
                "absolute_offset": absolute_offset,
                "section": "header" if absolute_offset < HEADER_SIZE else "payload",
                "payload_offset": absolute_offset - HEADER_SIZE if absolute_offset >= HEADER_SIZE else "",
                "byte_value": byte_value,
                "byte_hex": f"{byte_value:02x}",
            }
        )


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    if not args.input.exists():
        print(f"Input file not found: {args.input}", file=sys.stderr)
        return 2

    output_path = args.output or default_summary_output(args.input)
    bytes_output_path = args.bytes_output or default_bytes_output(args.input)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    if args.explode_bytes:
        bytes_output_path.parent.mkdir(parents=True, exist_ok=True)

    summary_fieldnames = [
        "sequence_id",
        "received_at_ms",
        "received_at_utc",
        "source_host",
        "source_port",
        "capture_byte_length",
        "decoded_byte_length",
        "header_ok",
        "header_size",
        "payload_size",
        "packet_format",
        "game_year",
        "game_major_version",
        "game_minor_version",
        "packet_version",
        "packet_id",
        "packet_name",
        "event_code",
        "session_uid",
        "session_time_s",
        "frame_identifier",
        "overall_frame_identifier",
        "player_car_index",
        "secondary_player_car_index",
        "payload_sha1",
        "decode_error",
    ]
    if args.include_payload_hex:
        summary_fieldnames.extend(["packet_hex", "payload_hex"])

    bytes_fieldnames = [
        "sequence_id",
        "packet_id",
        "packet_name",
        "event_code",
        "absolute_offset",
        "section",
        "payload_offset",
        "byte_value",
        "byte_hex",
    ]

    row_count = 0
    error_count = 0

    with (
        args.input.open("r", encoding="utf-8") as input_handle,
        output_path.open("w", encoding="utf-8", newline="") as summary_handle,
    ):
        summary_writer = csv.DictWriter(summary_handle, fieldnames=summary_fieldnames)
        summary_writer.writeheader()

        bytes_handle = None
        bytes_writer = None
        if args.explode_bytes:
            bytes_handle = bytes_output_path.open("w", encoding="utf-8", newline="")
            bytes_writer = csv.DictWriter(bytes_handle, fieldnames=bytes_fieldnames)
            bytes_writer.writeheader()

        try:
            for line_number, line in enumerate(input_handle, start=1):
                stripped = line.strip()
                if not stripped:
                    continue

                try:
                    record = json.loads(stripped)
                except json.JSONDecodeError as exc:
                    row_count += 1
                    error_count += 1
                    summary_writer.writerow(
                        {
                            "sequence_id": "",
                            "received_at_ms": "",
                            "received_at_utc": "",
                            "source_host": "",
                            "source_port": "",
                            "capture_byte_length": "",
                            "decoded_byte_length": "",
                            "header_ok": False,
                            "header_size": HEADER_SIZE,
                            "payload_size": "",
                            "packet_format": "",
                            "game_year": "",
                            "game_major_version": "",
                            "game_minor_version": "",
                            "packet_version": "",
                            "packet_id": "",
                            "packet_name": "",
                            "event_code": "",
                            "session_uid": "",
                            "session_time_s": "",
                            "frame_identifier": "",
                            "overall_frame_identifier": "",
                            "player_car_index": "",
                            "secondary_player_car_index": "",
                            "payload_sha1": "",
                            "decode_error": f"line {line_number}: invalid json: {exc}",
                        }
                    )
                    continue

                try:
                    payload_base64 = record["payload_base64"]
                    if not isinstance(payload_base64, str):
                        raise TypeError("payload_base64 must be a string")
                    packet_bytes = base64.b64decode(payload_base64, validate=True)
                except (KeyError, TypeError, ValueError, base64.binascii.Error) as exc:
                    row_count += 1
                    error_count += 1
                    summary_writer.writerow(
                        {
                            "sequence_id": record.get("sequence_id", ""),
                            "received_at_ms": record.get("received_at_ms", ""),
                            "received_at_utc": record.get("received_at_utc", ""),
                            "source_host": record.get("source_host", ""),
                            "source_port": record.get("source_port", ""),
                            "capture_byte_length": record.get("byte_length", ""),
                            "decoded_byte_length": "",
                            "header_ok": False,
                            "header_size": HEADER_SIZE,
                            "payload_size": "",
                            "packet_format": "",
                            "game_year": "",
                            "game_major_version": "",
                            "game_minor_version": "",
                            "packet_version": "",
                            "packet_id": "",
                            "packet_name": "",
                            "event_code": "",
                            "session_uid": "",
                            "session_time_s": "",
                            "frame_identifier": "",
                            "overall_frame_identifier": "",
                            "player_car_index": "",
                            "secondary_player_car_index": "",
                            "payload_sha1": "",
                            "decode_error": f"line {line_number}: invalid payload_base64: {exc}",
                        }
                    )
                    continue

                summary_row = build_summary_row(
                    record,
                    packet_bytes,
                    include_payload_hex=args.include_payload_hex,
                )
                summary_writer.writerow(summary_row)
                row_count += 1
                if summary_row["decode_error"]:
                    error_count += 1

                if bytes_writer is not None:
                    write_byte_rows(bytes_writer, summary_row, packet_bytes)
        finally:
            if bytes_handle is not None:
                bytes_handle.close()

    print(f"Summary CSV written to {output_path.resolve()}")
    if args.explode_bytes:
        print(f"Per-byte CSV written to {bytes_output_path.resolve()}")
    print(f"Processed {row_count} packets. Rows with decode issues: {error_count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
